pub(super) fn speech_score(features: [f64; 7]) -> f64 {
    VOTES
        .iter()
        .fold(BIAS, |score, &(dimension, cut, contribution)| {
            if features[dimension] >= cut {
                score + contribution
            } else {
                score
            }
        })
}

