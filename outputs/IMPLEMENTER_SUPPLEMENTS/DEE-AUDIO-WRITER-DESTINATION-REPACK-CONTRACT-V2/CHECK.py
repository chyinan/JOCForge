from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def require(condition: bool, label: str) -> None:
    if not condition:
        raise SystemExit(f"FAIL {label}")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


manifest_path = ROOT / "MANIFEST.json"
manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
require(sha256(manifest_path) == (ROOT / "MANIFEST.sha256").read_text(encoding="ascii").split()[0], "manifest hash")
require(manifest.get("package_id") == "DEE-AUDIO-WRITER-DESTINATION-REPACK-CONTRACT-V2", "package id")
payload = manifest.get("files")
require(isinstance(payload, list) and len(payload) == 4, "payload inventory")
actual_names = {path.name for path in ROOT.iterdir() if path.is_file() and path.name not in {"MANIFEST.json", "MANIFEST.sha256", "package_seal.json"}}
require(actual_names == {entry.get("file") for entry in payload}, "payload file set")
for entry in payload:
    path = ROOT / entry["file"]
    require(path.stat().st_size == entry["bytes"], f"size {entry['file']}")
    require(sha256(path) == entry["sha256"], f"hash {entry['file']}")

seal = json.loads((ROOT / "package_seal.json").read_text(encoding="utf-8"))
sealed = seal.get("files")
require(isinstance(sealed, list) and seal.get("file_count") == len(sealed), "seal inventory")
require({entry.get("file") for entry in sealed} == actual_names | {"MANIFEST.json", "MANIFEST.sha256"}, "sealed file set")
for entry in sealed:
    path = ROOT / entry["file"]
    require(path.stat().st_size == entry["bytes"], f"sealed size {entry['file']}")
    require(sha256(path) == entry["sha256"], f"sealed hash {entry['file']}")

evidence = json.loads((ROOT / "EVIDENCE.json").read_text(encoding="utf-8"))
vector = json.loads((ROOT / "INPUT-ONLY-VECTOR.json").read_text(encoding="utf-8"))
require(evidence["source_package"]["manifest_sha256"] == "a5a8d0246f1e7bda7d897db3609b884f6c185055f6357d66cbc83a1b8bbbe2fb", "source manifest binding")
require(evidence["ordered_consumer_handoff"]["producer_loop"].startswith("FUN_1800b7930 iterates"), "ordered record loop")
require(evidence["ordered_consumer_handoff"]["file_or_container_write_reached"] is False, "file writer boundary")
require(evidence["ordered_consumer_handoff"]["application_output_join"] == "UNBOUND_AFTER_FUN_1800b53b0_HANDOFF", "output boundary")
require(vector["runtime_execution"] == "NOT_RUN" and vector["product_audio_validation"] == "NOT_RUN", "no runtime validation claim")
require(evidence["execution_boundary"]["key_or_license_read"] is False, "private material boundary")

print("PASS: per-unit repack, ordered stream handoff, and post-consumer file boundary")
